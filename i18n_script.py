def add_import(content):
    if "import { useTranslation } from 'react-i18next';" not in content:
        content = content.replace("import { useState", "import { useTranslation } from 'react-i18next';\nimport { useState", 1)
        # Adding const { t } = useTranslation();
        content = re.sub(r'(export default function [a-zA-Z0-9_]+\([^)]*\)\s*\{)', r'\1\n  const { t } = useTranslation();', content)
    return content


